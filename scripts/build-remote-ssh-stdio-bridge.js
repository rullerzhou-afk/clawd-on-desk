"use strict";

const path = require("node:path");
const { build } = require("esbuild");

async function main() {
  const root = path.resolve(__dirname, "..");
  await build({
    entryPoints: [path.join(root, "scripts", "remote-ssh-stdio-bridge-entry.js")],
    outfile: path.join(root, "hooks", "remote-ssh-stdio-bridge.js"),
    bundle: true,
    platform: "node",
    format: "cjs",
    target: "node14",
    legalComments: "inline",
    banner: {
      js: "// Generated by scripts/build-remote-ssh-stdio-bridge.js. Do not edit by hand.",
    },
    logLevel: "info",
  });
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
