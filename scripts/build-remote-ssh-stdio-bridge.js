"use strict";

const path = require("node:path");
const { build } = require("esbuild");

function getBuildOptions() {
  const root = path.resolve(__dirname, "..");
  return {
    absWorkingDir: root,
    entryPoints: [path.join(root, "scripts", "remote-ssh-stdio-bridge-entry.js")],
    outfile: path.join(root, "hooks", "remote-ssh-stdio-bridge.js"),
    bundle: true,
    // Keep module paths stable when a worktree's node_modules is a symlink.
    preserveSymlinks: true,
    platform: "node",
    format: "cjs",
    target: "node14",
    legalComments: "inline",
    banner: {
      js: "// Generated by scripts/build-remote-ssh-stdio-bridge.js. Do not edit by hand.",
    },
    logLevel: "info",
  };
}

if (require.main === module) {
  build(getBuildOptions()).catch((err) => {
    console.error(err);
    process.exitCode = 1;
  });
}

module.exports = { getBuildOptions };
