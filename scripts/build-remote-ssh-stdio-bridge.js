"use strict";

const fs = require("node:fs");
const path = require("node:path");
const { build } = require("esbuild");

const root = path.resolve(__dirname, "..");

function readBridgeNotice(noticeText) {
  const sections = noticeText.replace(/\r\n/g, "\n").split(/^## /m).slice(1);
  const section = sections.find((text) => text.split("\n", 1)[0] === "Remote SSH stdio bridge");
  if (section === undefined) {
    throw new Error("NOTICE.md is missing the Remote SSH stdio bridge section");
  }
  return `## ${section.trimEnd()}`;
}

function validateBridgeNotice(notice, inputs) {
  const documented = new Set(
    Array.from(notice.matchAll(/`((?:@[^/\s`]+\/)?[^@/\s`]+)@[^\s`]+`/g), ([, name]) => name),
  );
  const missing = new Set();
  for (const input of inputs) {
    const parts = input.split(/[/\\]/);
    const index = parts.lastIndexOf("node_modules") + 1;
    if (index === 0) continue;
    const name = parts[index].startsWith("@") ? parts.slice(index, index + 2).join("/") : parts[index];
    if (!documented.has(name)) missing.add(name);
  }
  if (missing.size) {
    throw new Error(
      `NOTICE.md Remote SSH stdio bridge section is missing bundled packages: ${[...missing].sort().join(", ")}`,
    );
  }
}

async function buildRemoteSshBridge({
  noticeText = fs.readFileSync(path.join(root, "NOTICE.md"), "utf8"),
  write = true,
  logLevel = "info",
} = {}) {
  const notice = readBridgeNotice(noticeText);
  const { metafile, outputFiles: [output] } = await build({
    absWorkingDir: root,
    entryPoints: [path.join(root, "scripts", "remote-ssh-stdio-bridge-entry.js")],
    outfile: path.join(root, "hooks", "remote-ssh-stdio-bridge.js"),
    bundle: true,
    // Keep module paths stable when a worktree's node_modules is a symlink.
    preserveSymlinks: true,
    platform: "node",
    format: "cjs",
    target: "node14",
    legalComments: "inline",
    metafile: true,
    write: false,
    banner: {
      js: [
        "// Generated by scripts/build-remote-ssh-stdio-bridge.js. Do not edit by hand.",
        "/*!",
        notice.replaceAll("*/", "* /"),
        "*/",
      ].join("\n"),
    },
    logLevel,
  });

  const [bridge] = Object.values(metafile.outputs);
  validateBridgeNotice(notice, Object.keys(bridge.inputs));
  if (write) fs.writeFileSync(output.path, output.contents);
  return output;
}

if (require.main === module) {
  buildRemoteSshBridge().catch((err) => {
    console.error(err);
    process.exitCode = 1;
  });
}

module.exports = { buildRemoteSshBridge };
