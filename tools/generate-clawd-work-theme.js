#!/usr/bin/env node
"use strict";

// Generates the built-in "Clawd Work" theme (themes/clawd-work) from the plain
// Clawd artwork: the same crab in a charcoal suit, white collar, red tie and
// glasses.
//
// Every Clawd SVG paints its body with fill="#DE886D". This script swaps that
// colour for an SVG pattern drawn in the character's own 15x16 pixel grid, so
// the suit follows every animation transform (breathing, typing arms, jumps)
// without editing a single frame by hand. Glasses are part of the face, so the
// eyes still move and blink behind them.
//
// Flattened poses (sleeping, error) draw the body lower and wider; they use a
// separate pattern with only a jacket hem and tie.
//
// Usage: node tools/generate-clawd-work-theme.js [--check]
//   --check  exit 1 when the committed theme differs from a fresh generation.

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const SOURCE_DIR = path.join(ROOT, "assets", "svg");
const SOURCE_THEME = path.join(ROOT, "themes", "clawd", "theme.json");
const TARGET_DIR = path.join(ROOT, "themes", "clawd-work");
const BODY_FILL = 'fill="#DE886D"';
const SUIT_ID = "clawd-work-suit";
const FLAT_SUIT_ID = "clawd-work-suit-flat";

const SKIN = "#DE886D";
const JACKET = "#2B2F3A";
const LAPEL = "#3A4050";
const SHIRT = "#F4F4F0";
const TIE = "#C8323C";
const FRAME = "#15151A";
const LENS = "#FFFFFF";

// Standing body: torso x 2..13, y 6..13; eyes 1x2 at x 4 and x 10, y 8..10;
// arms at y 9..11 outside the torso; legs from y 13 down.
const STANDING_SUIT = [
  // Sleeves: arm pixels left and right of the torso.
  `<rect x="-60" y="8.5" width="62" height="60" fill="${JACKET}"/>`,
  `<rect x="13" y="8.5" width="60" height="60" fill="${JACKET}"/>`,
  // Jacket and trousers below the face.
  `<rect x="-60" y="11" width="140" height="60" fill="${JACKET}"/>`,
  // Lapels, collar and tie.
  `<rect x="5" y="11" width="1" height="1" fill="${LAPEL}"/>`,
  `<rect x="9" y="11" width="1" height="1" fill="${LAPEL}"/>`,
  `<rect x="6" y="11" width="3" height="1" fill="${SHIRT}"/>`,
  `<rect x="7" y="11" width="1" height="2" fill="${TIE}"/>`,
  // Glasses: two lenses around the eyes, a bridge and short temples.
  `<rect x="3.5" y="7.5" width="2" height="2.75" fill="${LENS}" fill-opacity="0.18"/>`,
  `<rect x="9.5" y="7.5" width="2" height="2.75" fill="${LENS}" fill-opacity="0.18"/>`,
  `<path d="M3 7h3v3.75h-3zM3.5 7.5v2.75h2v-2.75z" fill="${FRAME}" fill-rule="evenodd"/>`,
  `<path d="M9 7h3v3.75h-3zM9.5 7.5v2.75h2v-2.75z" fill="${FRAME}" fill-rule="evenodd"/>`,
  `<rect x="6" y="7.75" width="3" height="0.5" fill="${FRAME}"/>`,
  `<rect x="2" y="7.75" width="1" height="0.5" fill="${FRAME}"/>`,
  `<rect x="12" y="7.75" width="1" height="0.5" fill="${FRAME}"/>`,
];

// Flattened body: torso x 1..14, y 10..15 with the eyes around y 12..14.
const FLAT_SUIT = [
  `<rect x="-60" y="14" width="140" height="60" fill="${JACKET}"/>`,
  `<rect x="6" y="14" width="3" height="0.5" fill="${SHIRT}"/>`,
  `<rect x="7" y="14" width="1" height="1" fill="${TIE}"/>`,
];

// Files drawn in the flattened frame. Checked by --check against the source
// set so a new Clawd frame cannot silently get the wrong suit.
const FLAT_FILES = new Set([
  "clawd-error.svg",
  "clawd-sleeping.svg",
]);

function buildPattern(id, shapes) {
  // Pattern content is positioned relative to the tile origin, so the
  // translate puts content coordinates back in the character's grid.
  return [
    `<pattern id="${id}" patternUnits="userSpaceOnUse" x="-60" y="-60" width="140" height="140">`,
    `<g transform="translate(60 60)" shape-rendering="crispEdges">`,
    `<rect x="-60" y="-60" width="140" height="140" fill="${SKIN}"/>`,
    ...shapes,
    "</g>",
    "</pattern>",
  ].join("");
}

function transformSvg(name, source) {
  if (!source.includes(BODY_FILL)) {
    throw new Error(`${name}: no ${BODY_FILL} body fill to dress`);
  }
  const flat = FLAT_FILES.has(name);
  const patternId = flat ? FLAT_SUIT_ID : SUIT_ID;
  const defs = `<defs>${buildPattern(patternId, flat ? FLAT_SUIT : STANDING_SUIT)}</defs>`;
  // Swap the body fill before inserting the pattern: the pattern's own skin
  // layer uses the same colour and must not end up referencing itself.
  const dressed = source.split(BODY_FILL).join(`fill="url(#${patternId})"`);
  const openTag = dressed.match(/<svg\b[^>]*>/);
  if (!openTag) throw new Error(`${name}: no <svg> root`);
  const insertAt = openTag.index + openTag[0].length;
  return dressed.slice(0, insertAt)
    + `\n  <!-- Clawd Work: generated by tools/generate-clawd-work-theme.js -->\n  ${defs}`
    + dressed.slice(insertAt);
}

function buildThemeJson() {
  const theme = JSON.parse(fs.readFileSync(SOURCE_THEME, "utf8"));
  theme.name = "Clawd Work";
  theme.version = "1.0.0";
  theme.description = "Clawd dressed for the office: suit, tie and glasses. The default avatar for extra Claude profiles.";
  // The shared pet tint would recolour the suit along with the crab.
  if (theme.customization) theme.customization.petTint = false;
  return `${JSON.stringify(theme, null, 2)}\n`;
}

function generate() {
  const outputs = new Map();
  const names = fs.readdirSync(SOURCE_DIR).filter((name) => /^clawd-.*\.svg$/.test(name)).sort();
  for (const name of FLAT_FILES) {
    if (!names.includes(name)) throw new Error(`flat-pose file ${name} no longer exists in assets/svg`);
  }
  for (const name of names) {
    const source = fs.readFileSync(path.join(SOURCE_DIR, name), "utf8");
    outputs.set(path.join("assets", name), transformSvg(name, source));
  }
  outputs.set("theme.json", buildThemeJson());
  return outputs;
}

function main() {
  const check = process.argv.includes("--check");
  const outputs = generate();
  let stale = 0;
  for (const [rel, content] of outputs) {
    const target = path.join(TARGET_DIR, rel);
    let current = null;
    try { current = fs.readFileSync(target, "utf8"); } catch {}
    if (current === content) continue;
    stale++;
    if (check) {
      console.error(`stale: themes/clawd-work/${rel}`);
    } else {
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, content);
    }
  }
  if (check && stale) {
    console.error("Run: node tools/generate-clawd-work-theme.js");
    process.exitCode = 1;
  } else if (!check) {
    console.log(`clawd-work: ${outputs.size} files, ${stale} updated`);
  }
}

if (require.main === module) main();

module.exports = { FLAT_FILES, generate, transformSvg };
