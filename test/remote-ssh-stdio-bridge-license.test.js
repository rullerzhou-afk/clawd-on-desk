"use strict";

const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const test = require("node:test");
const vm = require("node:vm");

const { buildRemoteSshBridge } = require("../scripts/build-remote-ssh-stdio-bridge");

const root = path.join(__dirname, "..");
const notice = fs.readFileSync(path.join(root, "NOTICE.md"), "utf8").replace(/\r\n/g, "\n");
const bridgeHeading = "## Remote SSH stdio bridge";

test("PR #1366 follow-up: bundled bridge contains the complete NOTICE section", () => {
  const start = notice.indexOf(`\n${bridgeHeading}\n`);
  assert.notEqual(start, -1);
  const end = notice.indexOf("\n## ", start + 1);
  const section = notice.slice(start + 1, end === -1 ? undefined : end).trimEnd();
  const bridge = fs.readFileSync(path.join(root, "hooks", "remote-ssh-stdio-bridge.js"), "utf8")
    .replace(/\r\n/g, "\n");
  const header = bridge.match(
    /^\/\/ Generated by scripts\/build-remote-ssh-stdio-bridge\.js\. Do not edit by hand\.\n\/\*!\n([\s\S]*?)\n\*\/\n/,
  );
  assert.ok(header, "bridge must start with a retained license comment after the generated banner");
  assert.equal(header[1], section.replaceAll("*/", "* /"));
});

test("PR #1366 follow-up: bridge build rejects NOTICE without a bridge section", async () => {
  await assert.rejects(
    () => buildRemoteSshBridge({
      noticeText: notice.replace(bridgeHeading, "## Other section"),
      write: false,
    }),
    /NOTICE\.md is missing the Remote SSH stdio bridge section/,
  );
});

test("PR #1366 follow-up: bridge build rejects a bundled package without a NOTICE entry", async () => {
  const missingPackageNotice = notice.replace("`multiplex@", "`other-multiplex@");
  assert.notEqual(missingPackageNotice, notice);
  await assert.rejects(
    () => buildRemoteSshBridge({ noticeText: missingPackageNotice, write: false, logLevel: "silent" }),
    /NOTICE\.md Remote SSH stdio bridge section is missing bundled packages: multiplex$/,
  );
});

test("PR #1366 follow-up: bridge build escapes comment terminators in NOTICE", async () => {
  const output = await buildRemoteSshBridge({
    noticeText: notice.replace(bridgeHeading, `${bridgeHeading}\n\nLicense marker: */`),
    write: false,
    logLevel: "silent",
  });
  assert.ok(output.text.includes("License marker: * /"));
  assert.doesNotThrow(() => new vm.Script(output.text));
});
